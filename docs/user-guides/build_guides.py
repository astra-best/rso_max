def _set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def _set_cell_margins(cell, top=110, start=120, bottom=110, end=120) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for name, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tc_mar.find(qn(f"w:{name}"))
        if node is None:
            node = OxmlElement(f"w:{name}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def _set_borders(table) -> None:
    tbl_pr = table._tbl.tblPr
    borders = tbl_pr.first_child_found_in("w:tblBorders")
    if borders is None:
        borders = OxmlElement("w:tblBorders")
        tbl_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = qn(f"w:{edge}")
        node = borders.find(tag)
        if node is None:
            node = OxmlElement(f"w:{edge}")
            borders.append(node)
        node.set(qn("w:val"), "single")
        node.set(qn("w:sz"), "6")
        node.set(qn("w:color"), BORDER)


def _repeat_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    hdr = OxmlElement("w:tblHeader")
    hdr.set(qn("w:val"), "true")
    tr_pr.append(hdr)


def _cant_split(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    tr_pr.append(OxmlElement("w:cantSplit"))


def _keep_with_next(paragraph) -> None:
    paragraph.paragraph_format.keep_with_next = True


def _page_number(paragraph) -> None:
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = paragraph.add_run("Страница ")
    run.font.name = "Aptos"
    run.font.size = Pt(9)
    fld = OxmlElement("w:fldSimple")
    fld.set(qn("w:instr"), "PAGE")
    paragraph._p.append(fld)


def setup_document(title: str, subtitle: str, scope: str, *, stand_field: bool = True) -> Document:
    doc = Document()
    section = doc.sections[0]
    section.page_width = Cm(21.0)
    section.page_height = Cm(29.7)
    section.top_margin = Cm(2.1)
    section.bottom_margin = Cm(2.0)
    section.left_margin = Cm(2.25)
    section.right_margin = Cm(2.25)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Aptos"
    normal.font.size = Pt(11)
    normal.font.color.rgb = BLACK
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Aptos")
    normal.paragraph_format.space_after = Pt(6)
    normal.paragraph_format.line_spacing = 1.12

    title_style = styles["Title"]
    title_style.font.name = "Aptos Display"
    title_style.font.size = Pt(28)
    title_style.font.bold = True
    title_style.font.color.rgb = BLACK
    title_style._element.rPr.rFonts.set(qn("w:eastAsia"), "Aptos Display")
    title_style.paragraph_format.space_after = Pt(14)
    title_ppr = title_style._element.get_or_add_pPr()
    title_border = title_ppr.find(qn("w:pBdr"))
    if title_border is not None:
        title_ppr.remove(title_border)

    for name, size, before, after in (
        ("Heading 1", 18, 16, 7),
        ("Heading 2", 14, 12, 5),
        ("Heading 3", 11.5, 9, 3),
    ):
        style = styles[name]
        style.font.name = "Aptos Display"
        style.font.size = Pt(size)
        style.font.bold = True
        style.font.color.rgb = BLACK
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Aptos Display")
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.keep_with_next = True

    footer = section.footer
    footer.is_linked_to_previous = False
    p = footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    r = p.add_run("РСО MAX • тестирование")
    r.font.name = "Aptos"
    r.font.size = Pt(9)
    r.font.color.rgb = RGBColor(89, 89, 89)
    tab_stops = p.paragraph_format.tab_stops
    tab_stops.add_tab_stop(Cm(14.5))
    p.add_run("\t")
    _page_number(p)

    p = doc.add_paragraph(style="Title")
    direct_border = p._p.get_or_add_pPr().find(qn("w:pBdr"))
    if direct_border is not None:
        p._p.get_or_add_pPr().remove(direct_border)
    p.add_run(title)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(18)
    r = p.add_run(subtitle)
    r.bold = True
    r.font.size = Pt(13)

    meta = doc.add_table(rows=0, cols=2)
    meta.alignment = WD_TABLE_ALIGNMENT.LEFT
    meta.autofit = False
    for label, value in (
        ("Назначение", scope),
        ("Адрес тестового стенда", "________________________________________" if stand_field else "Не требуется"),
        ("Версия", "________________________________________"),
        ("Дата тестирования", "________________________________________"),
    ):
        row = meta.add_row()
        row.cells[0].width = Cm(4.2)
        row.cells[1].width = Cm(12.0)
        row.cells[0].text = label
        row.cells[1].text = value
        row.cells[0].paragraphs[0].runs[0].bold = True
    format_table(meta, header=False)

    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(8)
    p.add_run("Область руководства. ").bold = True
    p.add_run(scope)
    p = doc.add_paragraph()
    p.add_run("Для тестирования. ").bold = True
    p.add_run(
        "Работайте только с выданными тестовыми данными. Не вводите реальные пароли, "
        "персональные данные или документы, если это отдельно не согласовано с владельцем стенда."
    )
    doc.add_page_break()
    return doc


def format_table(table, *, header: bool = True, widths: list[float] | None = None) -> None:
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    _set_borders(table)
    if header and table.rows:
        _repeat_header(table.rows[0])
    for row_idx, row in enumerate(table.rows):
        _cant_split(row)
        for col_idx, cell in enumerate(row.cells):
            if widths and col_idx < len(widths):
                cell.width = Cm(widths[col_idx])
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            _set_cell_margins(cell)
            if header and row_idx == 0:
                _set_cell_shading(cell, BLUE)
            elif row_idx % 2 == 0:
                _set_cell_shading(cell, PALE)
            for p in cell.paragraphs:
                p.paragraph_format.space_after = Pt(2)
                p.paragraph_format.line_spacing = 1.05
                for run in p.runs:
                    run.font.name = "Aptos"
                    run.font.size = Pt(9.5)
                    run.font.color.rgb = RGBColor(255, 255, 255) if header and row_idx == 0 else BLACK
                    if header and row_idx == 0:
                        run.bold = True


def table(doc: Document, headers: list[str], rows: list[list[str]], widths: list[float] | None = None):
    t = doc.add_table(rows=1, cols=len(headers))
    for idx, header in enumerate(headers):
        t.rows[0].cells[idx].text = header
    for values in rows:
        cells = t.add_row().cells
        for idx, value in enumerate(values):
            cells[idx].text = value
    format_table(t, widths=widths)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)
    return t


def heading(doc: Document, text: str, level: int = 1) -> None:
    doc.add_heading(text, level=level)


def para(doc: Document, text: str, lead: str | None = None) -> None:
    p = doc.add_paragraph()
    if lead:
        p.add_run(lead.rstrip()).bold = True
        p.add_run(" " + text)
    else:
        p.add_run(text)


def bullets(doc: Document, items: list[str], *, numbered: bool = False) -> None:
    for index, item in enumerate(items, start=1):
        if numbered:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.75)
            p.paragraph_format.first_line_indent = Cm(-0.55)
            p.add_run(f"{index}. {item}")
        else:
            p = doc.add_paragraph(item, style="List Bullet")
        p.paragraph_format.space_after = Pt(4)


def checklist(doc: Document, items: list[str]) -> None:
    for item in items:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.4)
        p.add_run(f"☐ {item}")


def toc(doc: Document, entries: list[tuple[str, int]]) -> None:
    heading(doc, "Содержание", 1)
    for text, level in entries:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.5 * (level - 1))
        p.paragraph_format.space_after = Pt(3)
        p.add_run(text)
    doc.add_page_break()


